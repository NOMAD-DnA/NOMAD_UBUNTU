#!/usr/bin/env python3
"""Board time: Pi5 is the time reference, Jetson and Pi4 follow it with chrony.

install (root): chrony from the Ubuntu archive, role config, systemd-timesyncd
off, persistent Pi5<->Jetson direct cable address (10.77.0.2 / 10.77.0.1).
check (no root): this board's own readiness before modules start. A client must
follow a Pi5 address with |offset| <= 5 ms; Pi5 must be serving.
pi5_address (root, followers): the GUI passes the Pi5 address it just reached
when classroom DHCP gave Pi5 a new one; peers + chrony sources are updated.

Clock steps are allowed only right after chrony starts (makestep 0.1 3); after
that chrony only slews, so the clock never jumps while modules run.
Python 3.8 compatible (Jetson).
"""
import ipaddress
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

FEATURE = 'nomad-board-time-20261111-1'
MARKER = 'NOMAD_TIME_RESULT='
INSTALL_DIR = Path('/usr/local/lib/nomad-network')
INSTALLED = INSTALL_DIR / 'time_agent.py'
CHRONY_CONF = Path('/etc/chrony/chrony.conf')
PEERS = Path('/etc/nomad/network-peers.json')
WIRED_PROFILE = 'nomad-direct-20261105'
WIRED = {'pi5': ('10.77.0.2', '10.77.0.1'), 'jetson': ('10.77.0.1', '10.77.0.2')}
LIMIT_S = 0.005
MAX_UPDATE_AGE_S = 70.0
TRIAL_PROCESSES = ('oak_publisher', 'vio_backend_node', 'vio_frontend_node', 'fusion_node', 'nomad_mapper',
                   'nomad_runtime_manager', 'planner_node', 'controller_node', 'vesc_driver_node')


class TimeError(RuntimeError):
    pass


def run(args, timeout=30, check=True, env_extra=None):
    env = dict(os.environ, LC_ALL='C')
    if env_extra:
        env.update(env_extra)
    try:
        result = subprocess.run(args, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                universal_newlines=True, timeout=timeout, env=env)
    except (OSError, subprocess.TimeoutExpired):
        raise TimeError('command_timeout_or_unavailable') from None
    if check and result.returncode:
        raise TimeError('command_failed')
    return result.stdout.strip()


def board_role():
    model = Path('/proc/device-tree/model').read_text().replace('\x00', '').strip()
    for text, role in (('Raspberry Pi 4', 'pi4'), ('Raspberry Pi 5', 'pi5'), ('Jetson', 'jetson'), ('Xavier', 'jetson')):
        if text in model:
            return role
    raise TimeError('unsupported_board')


def pi5_addresses(role, peers_path=None):
    """Pi5 addresses a client may follow: direct cable, classroom, laptop hotspots."""
    peers_path = peers_path or PEERS
    out = []
    if role == 'jetson':
        out.append(WIRED['pi5'][0])
    try:
        value = json.loads(Path(peers_path).read_text())
    except (OSError, ValueError):
        value = {}
    candidates = [value.get('pi5')] + [n.get('pi5') for n in value.get('networks', []) if isinstance(n, dict)]
    for item in candidates:
        try:
            address = str(ipaddress.IPv4Address(item))
        except (ValueError, TypeError):
            continue
        if address not in out:
            out.append(address)
    return out


def chrony_config(role, servers):
    lines = ['# Generated by NOMAD board time setup (' + FEATURE + '). Original: chrony.conf.nomad-orig',
             'driftfile /var/lib/chrony/chrony.drift',
             '# Step only during the first updates after chronyd starts; slew afterwards.',
             'makestep 0.1 3',
             'rtcsync']
    if role == 'pi5':
        lines += ['# Pi5 is the NOMAD time reference. Internet NTP when reachable (classroom);',
                  '# otherwise it keeps serving its own clock so the boards stay together.',
                  'pool ntp.ubuntu.com iburst maxsources 2',
                  'local stratum 8',
                  'allow 10.0.0.0/8', 'allow 172.16.0.0/12', 'allow 192.168.0.0/16']
    else:
        if not servers:
            raise TimeError('pi5_address_unknown')
        lines.append('# Follow Pi5 only. Direct cable first on Jetson.')
        for index, address in enumerate(servers):
            prefer = ' prefer' if role == 'jetson' and index == 0 else ''
            lines.append('server {} iburst minpoll 1 maxpoll 4{}'.format(address, prefer))
    return '\n'.join(lines) + '\n'


def parse_tracking(text):
    """chronyc -c tracking -> dict (CSV: refid,name,stratum,reftime,system,last,rms,...,leap)."""
    parts = text.strip().split(',')
    if len(parts) < 14:
        raise TimeError('tracking_unavailable')
    return {'reference': parts[1], 'stratum': int(parts[2]), 'reference_time': float(parts[3]),
            'system_offset_s': float(parts[4]), 'last_offset_s': float(parts[5]), 'rms_offset_s': float(parts[6]),
            'leap': parts[13]}


def evaluate(role, tracking, servers, now):
    """Board's own decision. Returns (ok, reason)."""
    if role == 'pi5':
        return True, 'reference_serving' if tracking['leap'] != 'Not synchronised' else 'reference_serving_local_clock'
    if tracking['leap'] == 'Not synchronised' or tracking['reference'] not in servers:
        return False, 'not_following_pi5'
    if now - tracking['reference_time'] > MAX_UPDATE_AGE_S:
        return False, 'pi5_update_stale'
    if abs(tracking['system_offset_s']) > LIMIT_S or abs(tracking['last_offset_s']) > LIMIT_S:
        return False, 'offset_over_5ms'
    return True, 'following_pi5_within_5ms'


def check():
    role = board_role()
    result = {'ok': False, 'feature': FEATURE, 'board': role, 'limit_ms': LIMIT_S * 1000}
    if shutil.which('chronyc') is None:
        result['reason'] = 'chrony_not_installed'
        return result
    if run(['systemctl', 'is-active', 'chrony'], check=False) != 'active':
        result['reason'] = 'chrony_not_running'
        return result
    servers = pi5_addresses(role)
    tracking = parse_tracking(run(['chronyc', '-c', '-n', 'tracking'], timeout=10))
    ok, reason = evaluate(role, tracking, servers, time.time())
    result.update(ok=ok, reason=reason, reference=tracking['reference'], stratum=tracking['stratum'],
                  offset_ms=round(tracking['system_offset_s'] * 1000, 3),
                  last_offset_ms=round(tracking['last_offset_s'] * 1000, 3),
                  update_age_s=round(time.time() - tracking['reference_time'], 1), servers=servers)
    if role in WIRED:
        result['wired'] = wired_state(role)
    return result


def wired_state(role):
    try:
        persistent = run(['nmcli', '-g', 'connection.autoconnect,ipv4.addresses', 'connection', 'show', WIRED_PROFILE],
                         check=False).splitlines()
        address = run(['ip', '-4', '-o', 'addr', 'show', 'dev', 'eth0'], check=False)
    except TimeError:
        return 'unknown'
    on_link = (WIRED[role][0] + '/30') in address
    saved = len(persistent) == 2 and persistent[0] == 'yes' and persistent[1] == WIRED[role][0] + '/30'
    return ('fixed' if saved else 'temporary') + ('_up' if on_link else '_down')


def trial_running():
    out = run(['ps', '-eo', 'comm='], check=False).split()
    return sorted({p for p in out if p in TRIAL_PROCESSES})


def fix_wired(role):
    address, _ = WIRED[role]
    existing = run(['nmcli', '-g', 'ipv4.addresses', 'connection', 'show', WIRED_PROFILE], check=False)
    if existing:
        if existing != address + '/30':
            raise TimeError('wired_profile_mismatch')
        # Modify without --temporary saves an in-memory profile to disk; the
        # active link is not re-activated, so a running cable stays up.
        run(['nmcli', 'connection', 'modify', WIRED_PROFILE, 'connection.autoconnect', 'yes',
             'connection.autoconnect-priority', '100', 'ipv4.never-default', 'yes'])
    else:
        run(['nmcli', 'connection', 'add', 'type', 'ethernet', 'ifname', 'eth0', 'con-name', WIRED_PROFILE,
             'ipv4.method', 'manual', 'ipv4.addresses', address + '/30', 'ipv4.never-default', 'yes',
             'ipv6.method', 'disabled', 'connection.autoconnect', 'yes', 'connection.autoconnect-priority', '100'])
        run(['nmcli', '-w', '15', 'connection', 'up', WIRED_PROFILE], timeout=25, check=False)
    return wired_state(role)


def my_networks():
    """IPv4 networks of this board's interfaces (no loopback/docker/cable)."""
    out = []
    for line in run(['ip', '-4', '-o', 'addr', 'show'], check=False).splitlines():
        parts = line.split()
        if len(parts) < 4 or parts[1] == 'lo' or parts[1].startswith(('docker', 'br-', 'veth')):
            continue
        try:
            network = ipaddress.IPv4Interface(parts[3]).network
        except ValueError:
            continue
        if network.prefixlen < 31 and not network.overlaps(ipaddress.IPv4Network('10.77.0.0/30')):
            out.append(network)
    return out


def store_pi5_address(address, peers_path=None):
    """Put the current Pi5 address in network-peers.json: the matching laptop
    hotspot entry if its cidr contains it, otherwise the classroom (top-level)."""
    peers_path = peers_path or PEERS
    try:
        value = json.loads(Path(peers_path).read_text())
        if not isinstance(value, dict):
            value = {}
    except (OSError, ValueError):
        value = {}
    ip = ipaddress.IPv4Address(address)
    target = value
    for entry in value.get('networks', []):
        try:
            if isinstance(entry, dict) and ip in ipaddress.IPv4Network(entry.get('cidr', ''), strict=False):
                target = entry
                break
        except (ValueError, TypeError):
            continue
    previous = target.get('pi5')
    if previous == address:
        return previous
    target['pi5'] = address
    path = Path(peers_path)
    path.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
    temporary = path.with_name('.' + path.name + '.tmp')
    temporary.write_text(json.dumps(value) + '\n')
    os.chmod(str(temporary), 0o644)
    os.replace(str(temporary), str(path))
    return previous


def chrony_sources():
    """Addresses chronyd currently polls (chronyc -c sources: mode,state,address,...)."""
    found = []
    for line in run(['chronyc', '-c', '-n', 'sources'], timeout=10, check=False).splitlines():
        parts = line.split(',')
        if len(parts) > 2 and parts[0] == '^':
            found.append(parts[2])
    return found


def update_pi5(address, wait_s=25.0):
    """Follower learns Pi5's current address (given by the GUI, which just
    reached Pi5 there). Saved for reboots (peers + chrony.conf) and applied to
    the running chronyd with chronyc add/delete: no restart, no forced step."""
    if os.geteuid() != 0:
        raise TimeError('root_required')
    role = board_role()
    if role == 'pi5':
        raise TimeError('invalid_request')
    try:
        ip = ipaddress.IPv4Address(address)
    except (ValueError, TypeError):
        raise TimeError('invalid_pi5_address') from None
    if not ip.is_private or ip.is_loopback or ip in ipaddress.IPv4Network('10.77.0.0/30'):
        raise TimeError('invalid_pi5_address')
    if not any(ip in network for network in my_networks()):
        raise TimeError('pi5_address_not_on_my_network')
    running = trial_running()
    if running:
        raise TimeError('trial_running:' + ','.join(running))
    if shutil.which('chronyc') is None or not CHRONY_CONF.exists():
        raise TimeError('chrony_not_installed')
    store_pi5_address(str(ip))
    servers = pi5_addresses(role)
    CHRONY_CONF.write_text(chrony_config(role, servers))
    current = chrony_sources()
    for old in current:
        if old not in servers:
            run(['chronyc', 'delete', old], timeout=10, check=False)
    for index, new in enumerate(servers):
        if new not in current:
            options = ['iburst', 'minpoll', '1', 'maxpoll', '4'] + (['prefer'] if role == 'jetson' and index == 0 else [])
            run(['chronyc', 'add', 'server', new] + options, timeout=10)
    deadline = time.time() + wait_s
    value = check()
    while not value.get('ok') and time.time() < deadline:
        time.sleep(2)
        value = check()
    value.update(updated=True, pi5_address=str(ip))
    return value


def install(source):
    if os.geteuid() != 0:
        raise TimeError('root_required')
    role = board_role()
    running = trial_running()
    if running:
        raise TimeError('trial_running:' + ','.join(running))
    servers = pi5_addresses(role)
    config = chrony_config(role, servers)
    if shutil.which('chronyd') is None:
        run(['apt-get', '-o', 'DPkg::Lock::Timeout=180', 'install', '-y', '--no-install-recommends', 'chrony'],
            timeout=600, env_extra={'DEBIAN_FRONTEND': 'noninteractive'})
    original = CHRONY_CONF.with_name('chrony.conf.nomad-orig')
    if CHRONY_CONF.exists() and not original.exists():
        shutil.copy2(str(CHRONY_CONF), str(original))
    CHRONY_CONF.write_text(config)
    run(['systemctl', 'disable', '--now', 'systemd-timesyncd'], check=False)
    run(['systemctl', 'enable', 'chrony'], check=False)
    run(['systemctl', 'restart', 'chrony'])
    INSTALL_DIR.mkdir(mode=0o755, parents=True, exist_ok=True)
    if Path(source).resolve() != INSTALLED.resolve():
        shutil.copyfile(source, str(INSTALLED))
        os.chmod(str(INSTALLED), 0o755)
    wired = fix_wired(role) if role in WIRED else 'none'
    time.sleep(6)
    value = check()
    value.update(installed=True, wired=wired, servers=servers)
    return value


def main():
    if sys.argv[1:] == ['--check']:
        print(MARKER + json.dumps(check()), flush=True)
        return
    if len(sys.argv) == 3 and sys.argv[1] == '--request-file':
        path = Path(sys.argv[2])
        try:
            request = json.loads(path.read_text()) if path.is_file() and path.stat().st_size < 4096 else {}
        finally:
            try:
                path.unlink()
            except OSError:
                pass
        role = board_role()
        if request.get('board') != role:
            raise TimeError('wrong_board')
        if request.get('action') == 'install':
            value = install(os.path.abspath(__file__))
        elif request.get('action') == 'status':
            value = check()
        elif request.get('action') == 'pi5_address':
            value = update_pi5(request.get('address'))
        else:
            raise TimeError('invalid_request')
        print(MARKER + json.dumps(value), flush=True)
        return
    raise TimeError('invalid_request')


if __name__ == '__main__':
    try:
        main()
    except Exception as exc:
        reason = str(exc) if isinstance(exc, TimeError) else 'agent_error'
        print(MARKER + json.dumps({'ok': False, 'feature': FEATURE, 'reason': reason}), flush=True)
        sys.exit(1)
